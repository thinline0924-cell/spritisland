// 経済の数字を一日すすめる
export function stepEconomy(w) {
  const e = w.eco;
  const d = dateOf(w.day);
  if (d.wd === 0 || d.wd === 6) return null;
  const prev = { ...e };
  e.mood = clamp(e.mood * 0.97 + R.normal(0, 0.08), -1.2, 1.2);
  e.nikkei = Math.round(e.nikkei * (1 + R.normal(0.0002 + e.mood * 0.002, 0.012)));
  e.usd = clamp(e.usd + R.normal(0, 0.55), 125, 175);
  e.diesel = clamp(e.diesel + R.normal((e.usd - 150) * 0.004, 0.45), 130, 200);
  e.rice = clamp(e.rice + R.normal(0.02, 0.35), 70, 170);
  e.cpi = e.cpi + R.normal(0.008, 0.01);
  return prev;
}

