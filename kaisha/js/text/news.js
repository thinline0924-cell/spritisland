function vars(w, tpl) {
  const d = dateOf(w.day);
  const v = {
    x: R.int(2, 4), y: d.y + R.int(2, 6), m: d.m === 1 ? 12 : d.m - 1, n: R.int(3, 48), town: R.pick(TOWNS), d: d.d, age: R.pick([70, 80]),
    a: R.int(0, 3), b: R.int(0, 3), school: R.pick(SCHOOLS), r: (w.eco.rate).toFixed(2), updown: R.pick(['引き上げる', '据え置く']),
    usd: Math.round(w.eco.usd), month: `${d.m === 12 ? 1 : d.m + 1}月`,
  };
  if (/ガソリン/.test(tpl)) v.n = Math.round(w.eco.diesel + 12);
  if (/コメの店頭/.test(tpl)) v.n = Math.round(3200 + (w.eco.rice - 100) * 35);
  if (/最低賃金/.test(tpl)) v.n = R.int(1020, 1110);
  if (/人口/.test(tpl)) v.n = R.pick([76, 75, 74]);
  if (/x}倍/.test(tpl)) v.x = (R.f(2.5, 4.2)).toFixed(2);
  if (/賃上げ率/.test(tpl)) v.x = (R.f(3.4, 4.9)).toFixed(2);
  return v;
}
const sub = (tpl, v) => tpl.replace(/\$\{(\w+)\}/g, (_, k) => v[k] ?? '');
function pickFrom(bank, w) {
  const m = dateOf(w.day).m;
  const cands = bank.filter(x => !x[2] || x[2].includes(m));
  const it = R.pick(cands);
  const v = vars(w, it[0] + it[1]);
  return { head: sub(it[0], v), body: sub(it[1], v) };
}

export function makePaper(w, prevEco) {
  const d = dateOf(w.day);
  const arts = (w.pendingNews || []).splice(0);
  const e = w.eco;
  const p = { day: w.day, date: fmtDate(d), no: 28000 + w.day, items: [] };
  // 1面
  const big = arts.find(a => a.big) || arts.find(a => a.company);
  if (big) { p.top = big; arts.splice(arts.indexOf(big), 1); }
  else if (R.chance(0.35)) p.top = { sec: '総合', ...pickFrom(NATIONAL, w) };
  else p.top = { sec: '県内', ...pickFrom(LOCAL, w) };
  for (const a of arts) p.items.push(a);
  const nl = R.int(2, 3);
  for (let i = 0; i < nl; i++) p.items.push({ sec: '県内', ...pickFrom(LOCAL, w) });
  p.items.push({ sec: '経済', ...pickFrom(R.chance(0.6) ? INDUSTRY : NATIONAL, w) });
  // 重複を除く
  const seen = new Set(); p.items = p.items.filter(a => !seen.has(a.head) && seen.add(a.head) && a.head !== p.top.head);
  // 市況
  if (prevEco) {
    const dn = e.nikkei - prevEco.nikkei;
    p.market = { nikkei: e.nikkei, dn, usd: e.usd, diesel: e.diesel, rice: e.rice };
    p.items.push({ sec: '市況', head: `日経平均、${Math.abs(dn) < 50 ? '小動き' : dn > 0 ? (dn > 600 ? '大幅続伸' : '反発') : (dn < -600 ? '急落' : '続落')} ${dn >= 0 ? '+' : '△'}${Math.abs(dn).toLocaleString()}円`, body: `日経平均株価の終値は${e.nikkei.toLocaleString()}円。円相場は1ドル=${e.usd.toFixed(1)}円前後。${dn < -600 ? '米国市場の下落を受けて売りが広がった。' : dn > 600 ? '半導体関連株が相場を押し上げた。' : '方向感に乏しい展開だった。'}`, small: true });
  }
  // おくやみ
  p.okuyami = [];
  for (let i = 0; i < R.int(4, 8); i++) {
    const g = R.chance(0.5) ? 'm' : 'f';
    p.okuyami.push(`${R.pick(SEI)} ${R.pick(MEI[g].old)}さん(${R.int(68, 101)})${R.pick(TOWNS)}`);
  }
  // 天気
  p.weather = w.weather ? { ...w.weather } : null;
  w.papers = w.papers || [];
  w.papers.unshift(p); if (w.papers.length > 30) w.papers.pop();
  return p;
}
